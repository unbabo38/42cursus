#include "libft.h"

int	ft_isalpha(int c)
{
	if (c < 0 || c > 127)
		return (0);
	if (('a' <= c && c <= 'z') || ('A' <= c && c <= 'Z'))
		return (1024);
	else
		return (0);
}
